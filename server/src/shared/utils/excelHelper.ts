import type * as ExcelJS from 'exceljs';

/**
 * Reusable layout and formatting utilities for generating professional Excel reports with ExcelJS.
 */

export interface HeaderOptions {
  title: string;
  subtitle: string;
  generatedBy: string;
  reportPeriod: string;
  numCols: number;
  /** 'FULL REPORT' (default) or 'FILTERED REPORT' */
  reportType?: string;
  /** Human-readable description of active filters, shown only when reportType is filtered */
  filtersApplied?: string;
}

export interface SummaryItem {
  label: string;
  value: number;
}

/**
 * Formats a date to DD/MM/YYYY HH:mm
 */
export function formatDateTime(date: Date | string): string {
  const d = new Date(date);
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  const hours = String(d.getHours()).padStart(2, '0');
  const minutes = String(d.getMinutes()).padStart(2, '0');
  return `${day}/${month}/${year} ${hours}:${minutes}`;
}

/**
 * Creates a professional title header at the top of a worksheet.
 */
export function createProfessionalHeader(sheet: ExcelJS.Worksheet, options: HeaderOptions): void {
  const { title, subtitle, generatedBy, reportPeriod, numCols, reportType, filtersApplied } = options;

  // Title Row (Row 2)
  const titleRow = sheet.getRow(2);
  titleRow.height = 32;
  const titleCell = titleRow.getCell(1);
  titleCell.value = title.toUpperCase();
  titleCell.font = {
    name: 'Segoe UI',
    size: 16,
    bold: true,
    color: { argb: 'FF1E293B' }, // Slate 800
  };
  titleCell.alignment = { horizontal: 'center', vertical: 'middle' };
  sheet.mergeCells(2, 1, 2, numCols);

  // Subtitle Row (Row 3)
  const subRow = sheet.getRow(3);
  subRow.height = 20;
  const subCell = subRow.getCell(1);
  subCell.value = subtitle;
  subCell.font = {
    name: 'Segoe UI',
    size: 12,
    bold: true,
    italic: true,
    color: { argb: 'FF475569' }, // Slate 600
  };
  subCell.alignment = { horizontal: 'center', vertical: 'middle' };
  sheet.mergeCells(3, 1, 3, numCols);

  // Metadata Info (Row 4)
  const metaRow = sheet.getRow(4);
  metaRow.height = 20;
  const metaCell = metaRow.getCell(1);
  const generatedAt = formatDateTime(new Date());
  metaCell.value = `Generated On: ${generatedAt}   |   Report Period: ${reportPeriod}   |   Generated By: ${generatedBy}`;
  metaCell.font = {
    name: 'Segoe UI',
    size: 9.5,
    color: { argb: 'FF64748B' }, // Slate 500
  };
  metaCell.alignment = { horizontal: 'center', vertical: 'middle' };
  sheet.mergeCells(4, 1, 4, numCols);

  // Report Type / Filters Row (Row 5)
  const isFiltered = (reportType || '').toUpperCase().includes('FILTER');
  const typeRow = sheet.getRow(5);
  typeRow.height = 20;
  const typeCell = typeRow.getCell(1);
  typeCell.value = isFiltered
    ? `Report Type: FILTERED REPORT   |   Filters Applied: ${filtersApplied || 'N/A'}`
    : `Report Type: ${(reportType || 'FULL REPORT').toUpperCase()}`;
  typeCell.font = {
    name: 'Segoe UI',
    size: 9.5,
    bold: true,
    italic: !isFiltered,
    color: { argb: isFiltered ? 'FFB45309' : 'FF64748B' }, // Amber 700 when filtered, Slate 500 otherwise
  };
  typeCell.alignment = { horizontal: 'center', vertical: 'middle' };
  sheet.mergeCells(5, 1, 5, numCols);

  // Add decorative bottom border under header block
  for (let c = 1; c <= numCols; c++) {
    const cell = typeRow.getCell(c);
    cell.border = {
      bottom: { style: 'medium', color: { argb: 'FFCBD5E1' } }, // Slate 300
    };
  }

  // Row 6 is left blank as spacing
  sheet.getRow(6).height = 12;
}

/**
 * Creates a clean summary statistics block on the worksheet.
 */
export function createSummaryTable(
  sheet: ExcelJS.Worksheet,
  startRow: number,
  title: string,
  stats: SummaryItem[],
): number {
  // Add section title
  const titleRow = sheet.getRow(startRow);
  titleRow.height = 20;
  const titleCell = titleRow.getCell(1);
  titleCell.value = title;
  titleCell.font = { name: 'Segoe UI', size: 11, bold: true, color: { argb: 'FF1E293B' } };
  titleCell.alignment = { horizontal: 'left', vertical: 'middle' };

  const headerRow = sheet.getRow(startRow + 1);
  headerRow.height = 24;
  
  const borderThin = { style: 'thin' as const, color: { argb: 'FFCBD5E1' } };
  const fillHeader = {
    type: 'pattern' as const,
    pattern: 'solid' as const,
    fgColor: { argb: 'FFF1F5F9' }, // Slate 100
  };

  // Populate headers
  stats.forEach((stat, idx) => {
    const colIdx = idx + 1;
    const cell = headerRow.getCell(colIdx);
    cell.value = stat.label;
    cell.font = { name: 'Segoe UI', size: 9.5, bold: true, color: { argb: 'FF475569' } };
    cell.fill = fillHeader;
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
    cell.border = { top: borderThin, left: borderThin, right: borderThin, bottom: borderThin };
  });

  const valueRow = sheet.getRow(startRow + 2);
  valueRow.height = 26;

  // Populate values
  stats.forEach((stat, idx) => {
    const colIdx = idx + 1;
    const cell = valueRow.getCell(colIdx);
    cell.value = stat.value;
    cell.font = { name: 'Segoe UI', size: 11, bold: true, color: { argb: 'FF0F172A' } };
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
    cell.border = { top: borderThin, left: borderThin, right: borderThin, bottom: borderThin };
  });

  // Return the row index after this block (includes spacing)
  sheet.getRow(startRow + 3).height = 15;
  return startRow + 4;
}

/**
 * Renders a stylized table and auto-formats columns, wraps text, sets sorting filter and freezes header.
 */
export function formatTable(
  sheet: ExcelJS.Worksheet,
  startRow: number,
  headers: string[],
  rows: any[][],
  columnAlignments?: ('left' | 'center' | 'right')[],
): void {
  const headerRow = sheet.getRow(startRow);
  headerRow.height = 28;

  const borderThin = { style: 'thin' as const, color: { argb: 'FFCBD5E1' } };
  
  // Grey background for table headers (Slate 200)
  const fillHeader = {
    type: 'pattern' as const,
    pattern: 'solid' as const,
    fgColor: { argb: 'FFE2E8F0' }, // Slate 200
  };

  // 1. Render Headers
  headers.forEach((h, idx) => {
    const cell = headerRow.getCell(idx + 1);
    cell.value = h;
    cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FF1E293B' } };
    cell.fill = fillHeader;
    cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true };
    cell.border = {
      top: borderThin,
      left: borderThin,
      right: borderThin,
      bottom: { style: 'medium' as const, color: { argb: 'FF94A3B8' } }, // Slate 400
    };
  });

  // 2. Render Data Rows
  const fillZebra = {
    type: 'pattern' as const,
    pattern: 'solid' as const,
    fgColor: { argb: 'FFF8FAFC' }, // Slate 50
  };

  rows.forEach((row, rIdx) => {
    const rowNum = startRow + 1 + rIdx;
    const sheetRow = sheet.getRow(rowNum);
    sheetRow.height = 22;

    row.forEach((val, cIdx) => {
      const cell = sheetRow.getCell(cIdx + 1);
      cell.value = val === null || val === undefined ? '—' : val;
      cell.font = { name: 'Segoe UI', size: 9.5, color: { argb: 'FF334155' } }; // Slate 700

      // Alignments
      const align = columnAlignments?.[cIdx] || 'left';
      cell.alignment = { horizontal: align, vertical: 'middle', wrapText: true };
      cell.border = { top: borderThin, left: borderThin, right: borderThin, bottom: borderThin };

      // Zebra striping for even rows
      if (rIdx % 2 === 1) {
        cell.fill = fillZebra;
      }
    });
  });

  // 3. Freeze table header row (split at startRow, freeze upper section)
  sheet.views = [
    {
      state: 'frozen',
      xSplit: 0,
      ySplit: startRow,
      topLeftCell: `A${startRow + 1}`,
      activeCell: `A${startRow + 1}`,
    },
  ];

  // 4. Enable Excel Filters on headers
  const numCols = headers.length;
  const numRows = rows.length;
  sheet.autoFilter = {
    from: { row: startRow, column: 1 },
    to: { row: startRow + numRows, column: numCols },
  };

  // 5. Auto Column Widths Calculation
  sheet.columns.forEach((column) => {
    let maxLength = 10; // min width
    if (column.eachCell) {
      column.eachCell({ includeEmpty: false }, (cell, rowNumber) => {
        // Skip header lines (1 to startRow - 1) for column width calculation to prevent merged headers from skewing it
        if (rowNumber < startRow) return;

        const cellValue = cell.value;
        if (cellValue) {
          const stringValue = String(cellValue);
          if (stringValue.length > maxLength) {
            maxLength = stringValue.length;
          }
        }
      });
    }
    // Set width with some padding
    column.width = Math.min(45, maxLength + 4);
  });
}

/**
 * Configures the page setups to be print-friendly
 */
export function applyPrintFormatting(sheet: ExcelJS.Worksheet, headerRowIndex: number): void {
  sheet.pageSetup = {
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0, // dynamic length
    printTitlesRow: `${headerRowIndex}:${headerRowIndex}`, // repeat table header on every page
    margins: {
      left: 0.5,
      right: 0.5,
      top: 0.75,
      bottom: 0.75,
      header: 0.3,
      footer: 0.3,
    },
  };
}

/**
 * Configures a native print header/footer on a worksheet.
 */
export function applyFooter(sheet: ExcelJS.Worksheet): void {
  const generatedAt = formatDateTime(new Date());
  sheet.headerFooter = {
    oddFooter: `&LGenerated by Sanjivani Blood Bank Management System&RReport Generated On: ${generatedAt}`,
    differentFirst: false,
  };
}
